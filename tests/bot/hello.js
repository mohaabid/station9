const mineflayer = require('mineflayer')
const bot = mineflayer.createBot({ host: '127.0.0.1', port: 25565, username: 'Tester', version: '1.20.4' })
bot.on('messagestr', m => console.log('CHAT', m))
bot.on('title', (t, type) => console.log('TITLE', type, t))
bot.on('actionBar', t => console.log('ACTIONBAR', t.toString()))
bot.on('spawn', () => { console.log('spawn', bot.entity.position, bot.game.gameMode) })
bot.on('error', e => console.log('ERR', e))
bot.on('kicked', e => console.log('KICK', e))
setTimeout(() => { console.log('pos', bot.entity.position); bot.quit(); process.exit(0) }, 20000)
